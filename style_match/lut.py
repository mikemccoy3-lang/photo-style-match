"""Bake a look profile into a portable .cube LUT.

A .cube LUT is a fixed function of input color only -- it has no notion
of "this whole photo is underexposed" or "this photo already has punchy
contrast." So this is an approximation: it assumes a neutral input
distribution per channel rather than adapting to each source photo's own
stats, the way `apply_profile` does. Treat it as a fast starting point for
Lightroom/Premiere, not a full substitute for running the profile per photo.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
from skimage import color

from .profile import LookProfile


def export_cube_lut(profile: LookProfile, path: Path, size: int = 33) -> None:
    axis = np.linspace(0, 1, size)
    r, g, b = np.meshgrid(axis, axis, axis, indexing="ij")
    rgb = np.stack([r, g, b], axis=-1)

    lab = color.rgb2lab(rgb)
    l, a, ch_b = lab[..., 0], lab[..., 1].copy(), lab[..., 2].copy()

    for i, channel in enumerate((a, ch_b), start=1):
        src_mean, src_std = channel.mean(), channel.std() or 1.0
        ref_mean, ref_std = profile.lab_mean[i], profile.lab_std[i]
        channel[:] = (channel - src_mean) / src_std * ref_std + ref_mean

    l_span = (l.max() - l.min()) or 1.0
    l_mapped = (l - l.min()) / l_span * (profile.white_point - profile.black_point) + profile.black_point

    graded_lab = np.stack([l_mapped, a, ch_b], axis=-1)
    graded_rgb = np.clip(color.lab2rgb(graded_lab), 0, 1)

    lines = [
        f"# Generated by photo-style-match from {len(profile.source_images)} reference image(s)",
        f"LUT_3D_SIZE {size}",
    ]
    # .cube spec: R varies fastest, then G, then B.
    for bi in range(size):
        for gi in range(size):
            for ri in range(size):
                pr, pg, pb = graded_rgb[ri, gi, bi]
                lines.append(f"{pr:.6f} {pg:.6f} {pb:.6f}")

    Path(path).write_text("\n".join(lines))
